#!/usr/bin/env python3.11
"""The blur each street deco's own SWF puts on its art, for js/deco-blur.js (G1174).

Flash drew a filter at its own size in screen px: a deco drawn at w x h scaled its art (DecoRenderer.as
syncRendererWithModel: decoAsset.scaleX = w / the SWF stage width) but never the BlurFilter on a
child, so a squashed deco kept its soft edge. build.py renders each deco once at its stage size, so
its blur is baked in at the stage's scale and a deco squashed to a fraction of its stage drew a hard
edge (Egret Taun Towers Basement's box_blur_1 under the ceiling: 255 px of a 633 px stage, a 75 px
blur drawn 30 px wide). js/deco-blur.js adds the blur the squash took away.

Writes public/js/deco-blur-data.js: { name: [stage w, stage h, blurX, blurY] } (stage px; the
largest BlurFilter a PlaceObject3 in the deco's SWF carries, 4 px or more), for every deco build.py
renders from a SWF (plan.json `swf`). Glitch-locations is data only: SWFs are parsed, never run.

Usage:
  python3.11 -I tools/deco-pipeline/deco-blurs.py --work <scratch dir>
  python3.11 -I tools/deco-pipeline/deco-blurs.py --work <scratch dir> --check   (exit 1 when stale)
"""
import argparse, json, os, struct, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.dont_write_bytecode = True
sys.path.insert(0, HERE)
import build  # noqa: E402
import swfinfo  # noqa: E402  (build.py puts tools/icon-hires on the path)
import audit  # noqa: E402

OUT_JS = os.path.join(build.PUBLIC, 'js', 'deco-blur-data.js')
MIN_BLUR = 4


def place_blurs(body, q):
    """[(blurX, blurY)] of the BlurFilters (id 1) on the PlaceObject3 whose data starts at q."""
    f1, f2 = body[q], body[q + 1]
    if not f2 & 0x01:
        return []
    p = q + 4
    if f2 & 0x08 or (f2 & 0x10 and f1 & 0x02):
        p = body.index(0, p) + 1
    if f1 & 0x02:
        p += 2
    if f1 & 0x04:
        r = swfinfo._Bits(body, p)
        if r.u(1): n = r.u(5); r.u(2 * n)
        if r.u(1): n = r.u(5); r.u(2 * n)
        n = r.u(5); r.u(2 * n)
        p = r.end()
    if f1 & 0x08:
        r = swfinfo._Bits(body, p)
        add, mult, n = r.u(1), r.u(1), r.u(4)
        r.u(4 * n * (add + mult))
        p = r.end()
    if f1 & 0x10:
        p += 2
    if f1 & 0x20:
        p = body.index(0, p) + 1
    if f1 & 0x40:
        p += 2
    out = []
    count = body[p]; p += 1
    sizes = {0: 23, 2: 15, 3: 27}
    for _ in range(count):
        fid = body[p]; p += 1
        if fid == 1:
            bx, by = struct.unpack_from('<ii', body, p)
            out.append((bx / 65536, by / 65536))
            p += 9
        elif fid in sizes:
            p += sizes[fid]
        else:
            break  # convolution, colour matrix, gradient filters: variable length, no blur after them we can read
    return out


def swf_blur(path):
    body, _ = swfinfo.swf_body(path)
    best = (0.0, 0.0)
    for code, q, _ in swfinfo.tags(body, swfinfo.rect_len(body) + 4, len(body)):
        if code == 70:
            for b in place_blurs(body, q):
                if max(b) > max(best):
                    best = b
    return best


def table(work):
    plan = build.read_plan()['decos']
    index = audit.bundle_index()
    out = {}
    for name in sorted(plan):
        row = plan[name]
        if not row.get('swf') or not row.get('stage'):
            continue
        bx, by = swf_blur(audit.swf_path(row['swf'], work, index))
        if max(bx, by) >= MIN_BLUR:
            out[name] = [round(row['stage'][0], 2), round(row['stage'][1], 2), round(bx, 2), round(by, 2)]
    return out


def js_text(rows):
    body = ',\n'.join(f'  {json.dumps(k)}: {json.dumps(v)}' for k, v in rows.items())
    return ('// Generated by tools/deco-pipeline/deco-blurs.py from the deco SWFs (tinyspeck/glitch-locations, CC0): never edit by hand.\n'
            '/**\n'
            ' * The blur a deco\'s own SWF puts on its art (G1174): { name: [stage w, stage h, blurX, blurY] }, stage px.\n'
            ' * js/deco-blur.js blurFix reads it.\n'
            ' */\n'
            f'export const DECO_BLURS = Object.freeze({{\n{body}\n}});\n')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--work', required=True)
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    os.makedirs(args.work, exist_ok=True)
    text = js_text(table(args.work))
    if args.check:
        old = open(OUT_JS).read() if os.path.exists(OUT_JS) else ''
        if old != text:
            print(f'{OUT_JS} is stale: run python3.11 -I tools/deco-pipeline/deco-blurs.py --work <dir>')
            sys.exit(1)
        print(f'deco blurs are current ({text.count(": [")} decos)')
        return
    open(OUT_JS, 'w').write(text)
    print(f'{text.count(": [")} decos with a blur -> {OUT_JS}')


if __name__ == '__main__':
    main()
