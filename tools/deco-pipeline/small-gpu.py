#!/usr/bin/env python3.11
"""Small-GPU copies of the street decos longer than 4096 px on a side (register row G765).

build.py ships every deco's 2x art as <name>.webp at the old PNG's pixel size. Eighteen of those
(Bliss's blur_landscape_piece_01, the Hell streets' patch_rough8, Kanva Ria's haze_gradient_01 and
the rest) are longer than 4096 px, and many Android GPUs take textures up to 4096 px on a side and
draw a bigger one black (#326, G748: the same failure on the vendor sheets). The 2x file stays as
it is, so a GPU that takes it draws the same pixels; this tool adds <name>@<res>x.webp beside it,
the same picture scaled (Lanczos, premultiplied) so its longer side is at most 4096 px, and
js/deco-hires.js decoUrl loads it where the GPU's MAX_TEXTURE_SIZE is below the 2x file. The copy
keeps the deco's logical size (js/textures.js reads the resolution from `@<res>x`); res is picked
with up to three decimals so that width / res and height / res land on the 2x file's size.

Every <name>.webp in the deco folder over the limit gets one (a published zone's gz_ art too).
plan-small.json records each copy's source hash, res, size and hash; js/deco-small-list.js is
generated from it.

Usage (python3.11 has numpy + Pillow; cwebp 1.6):
  python3.11 -I tools/deco-pipeline/small-gpu.py --work <scratch dir> [--force]
  python3.11 -I tools/deco-pipeline/small-gpu.py --check     (exit 1 on any problem)
"""
import argparse, hashlib, json, math, os, sys

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
sys.dont_write_bytecode = True  # no __pycache__ in tools/
sys.path.insert(0, HERE)
import build  # noqa: E402  (deco-pipeline: paths and encode)

OUT = build.OUT
PLAN = os.path.join(HERE, 'plan-small.json')
JS = os.path.join(build.PUBLIC, 'js', 'deco-small-list.js')

SETTINGS = {
    'version': 1,
    'max_side': 4096,   # longest side a small GPU takes (#326: MAX_TEXTURE_SIZE 4096 on many Android phones)
    'size_error': 0.25,  # largest logical px a copy's width / res or height / res may miss the 2x file by
}


def sha(path):
    return hashlib.sha256(open(path, 'rb').read()).hexdigest()[:16]


def copy_name(name, res):
    return f'{name}@{res:g}x.webp'


def pick_res(w, h, max_side=None):
    """The largest res (three decimals) whose copy fits max_side and whose round(w * res) / res and
    round(h * res) / res are within size_error of w and h; the closest fit when none is."""
    max_side = max_side or SETTINGS['max_side']
    top = math.floor(max_side / max(w, h) * 1000)
    best = None
    for k in range(top, max(1, top - 400), -1):
        r = k / 1000
        cw, ch = round(w * r), round(h * r)
        if max(cw, ch) > max_side:
            continue
        err = max(abs(cw / r - w), abs(ch / r - h))
        if err <= SETTINGS['size_error']:
            return r, [cw, ch], round(err, 4)
        if best is None or err < best[2]:
            best = (r, [cw, ch], round(err, 4))
    return best


def oversize():
    """{name: [w, h]} for every 2x deco file over max_side."""
    out = {}
    for f in sorted(os.listdir(OUT)):
        if not f.endswith('.webp') or '@' in f:
            continue
        with Image.open(os.path.join(OUT, f)) as im:
            w, h = im.size
        if max(w, h) > SETTINGS['max_side']:
            out[f[:-len('.webp')]] = [w, h]
    return out


def read_plan():
    if not os.path.exists(PLAN):
        return {'settings': SETTINGS, 'decos': {}}
    return json.load(open(PLAN))


def write_plan(p):
    p['decos'] = dict(sorted(p['decos'].items()))
    open(PLAN, 'w').write(json.dumps(p, indent=1) + '\n')


def js_text(p):
    rows = [[n, r['res'], max(r['size2'])] for n, r in sorted(p['decos'].items())]
    body = ',\n'.join(f'  [{json.dumps(n)}, [{res:g}, {side}]]' for n, res, side in rows)
    return (
        '/**\n'
        ' * Street decos whose 2x file is longer than SMALL_GPU_MAX_SIDE px on a side, each with\n'
        ' * <name>@<res>x.webp beside it: the same picture scaled to fit, for a GPU that takes no\n'
        ' * bigger texture (js/deco-hires.js decoUrl). name -> [res, longest side of the 2x file].\n'
        ' * Generated by tools/deco-pipeline/small-gpu.py; do not edit by hand.\n'
        ' */\n'
        f'export const SMALL_GPU_MAX_SIDE = {SETTINGS["max_side"]};\n\n'
        f'export const SMALL_GPU_DECOS = new Map([\n{body},\n]);\n'
    )


def cmd_build(args):
    p = read_plan()
    if p.get('settings') != SETTINGS:
        args.force = True
    p['settings'] = SETTINGS
    want = oversize()
    for n in list(p['decos']):
        if n not in want:
            old = os.path.join(OUT, copy_name(n, p['decos'][n]['res']))
            if os.path.exists(old):
                os.remove(old)
            del p['decos'][n]
    for n, (w, h) in want.items():
        src = os.path.join(OUT, n + '.webp')
        old = p['decos'].get(n)
        if old and not args.force and old['src_sha'] == sha(src) and os.path.exists(os.path.join(OUT, copy_name(n, old['res']))):
            continue
        res, size, err = pick_res(w, h)
        if old and old['res'] != res and os.path.exists(os.path.join(OUT, copy_name(n, old['res']))):
            os.remove(os.path.join(OUT, copy_name(n, old['res'])))
        with Image.open(src) as im:
            img = im.convert('RGBA').convert('RGBa').resize(tuple(size), Image.LANCZOS).convert('RGBA')
        dst = os.path.join(OUT, copy_name(n, res))
        nbytes, lossless, perr = build.encode(img, dst, os.path.join(args.work, 'enc'))
        p['decos'][n] = {
            'size2': [w, h], 'src_sha': sha(src), 'res': res, 'size': size, 'size_error': err,
            'bytes': nbytes, 'lossless': lossless, 'err': perr, 'sha': sha(dst),
        }
        print(f'{n}: {w}x{h} -> {copy_name(n, res)} {size[0]}x{size[1]} ({nbytes // 1024} KB)', flush=True)
    write_plan(p)
    open(JS, 'w').write(js_text(p))
    print(f'{len(p["decos"])} small-GPU copies')


def cmd_check(_args):
    problems = []
    p = read_plan()
    if p.get('settings') != SETTINGS:
        problems.append('plan-small.json was built with other settings; rebuild')
    want = oversize()
    for n, (w, h) in want.items():
        r = p['decos'].get(n)
        if not r:
            problems.append(f'{n}: {w}x{h} has no small-GPU copy (build)')
            continue
        if r['src_sha'] != sha(os.path.join(OUT, n + '.webp')):
            problems.append(f'{n}: {n}.webp changed since its copy was made (build)')
        dst = os.path.join(OUT, copy_name(n, r['res']))
        if not os.path.exists(dst):
            problems.append(f'{n}: missing {os.path.basename(dst)}')
            continue
        if sha(dst) != r['sha']:
            problems.append(f'{n}: {os.path.basename(dst)} is not the built file')
        with Image.open(dst) as im:
            cw, ch = im.size
        if max(cw, ch) > SETTINGS['max_side']:
            problems.append(f'{n}: {os.path.basename(dst)} is {cw}x{ch}, over {SETTINGS["max_side"]}')
        if abs(cw / r['res'] - w) > 0.5 or abs(ch / r['res'] - h) > 0.5:
            problems.append(f'{n}: {os.path.basename(dst)} at res {r["res"]:g} is not {w}x{h}')
    for n in p['decos']:
        if n not in want:
            problems.append(f'{n}: in plan-small.json but its 2x file fits (build drops it)')
    if not os.path.exists(JS) or open(JS).read() != js_text(p):
        problems.append('js/deco-small-list.js is stale (build)')
    for x in problems:
        print('  ' + x)
    print(f'{len(want)} decos over {SETTINGS["max_side"]} px; {len(problems)} problems')
    return 1 if problems else 0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--work', help='scratch dir for encoding')
    ap.add_argument('--force', action='store_true')
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    if args.check:
        sys.exit(cmd_check(args))
    if not args.work:
        ap.error('--work is required to build')
    cmd_build(args)


if __name__ == '__main__':
    main()
