/**
 * The Quarter's blocks for the realtime server (register G1186): quarter.go needs to know which
 * streets are quarter blocks and the lot numbers on each, so it can refuse a claim on a lot that
 * does not exist before it asks the site. From the game's own street JSON: every street whose
 * `quarter` names its lots (public/js/quarter.js quarterStreet, written by
 * tools/build-rebuilt-rooms.mjs).
 *
 * Run from the game repo root:
 *   node tools/build-realtime-quarters.mjs          (write)
 *   node tools/build-realtime-quarters.mjs --check  (fail when stale)
 * Writes data/quarters.json in the realtime server repo (go:embed in its quarter.go; found by
 * tools/repos.mjs: GRODDLE_SERVER_DIR, else ../groddle-afternoon-server).
 */

import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { requireServer, serverPath } from './repos.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outPath = serverPath('data', 'quarters.json');

/** Every quarter block in the street index: { tsid: { label, lots } }, sorted by tsid. */
export function quartersData() {
  const index = JSON.parse(readFileSync(join(root, 'public/assets/streets/index.json'), 'utf8')).streets;
  const streets = {};
  for (const tsid of Object.keys(index).sort()) {
    const row = index[tsid];
    if (!row?.file) continue;
    const street = JSON.parse(readFileSync(join(root, 'public', row.file), 'utf8'));
    if (!street.quarter?.lots?.length) continue;
    streets[tsid] = { label: street.label, lots: street.quarter.lots.map((l) => l.lot) };
  }
  return {
    about: 'Quarter blocks for quarter.go in groddle-afternoon-server. Generated by tools/build-realtime-quarters.mjs from the game\'s street JSON (street.quarter, public/js/quarter.js); do not edit by hand.',
    format: 'streets{tsid: {label, lots[] = the numbers on the doors}}',
    streets,
  };
}

async function main() {
  requireServer();
  const out = quartersData();
  const text = `${JSON.stringify(out)}\n`;
  const n = Object.keys(out.streets).length;
  if (process.argv.includes('--check')) {
    const now = await readFile(outPath, 'utf8').catch(() => '');
    if (now !== text) {
      console.error(`${outPath} is stale: run node tools/build-realtime-quarters.mjs`);
      process.exit(1);
    }
    console.log(`${outPath} is current (${n} quarter blocks)`);
    return;
  }
  await mkdir(dirname(outPath), { recursive: true });
  await writeFile(outPath, text);
  console.log(`${n} quarter blocks -> ${outPath}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) await main();
