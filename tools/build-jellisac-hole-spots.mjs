#!/usr/bin/env node
/**
 * G933 (#453, #460): a Jellisac the snaps never measured sits in its street's empty hole before one
 * is planned on a floor. Jellisacs live in the ground cutaway hollows (the location files' decos
 * ground_cutaway_hollow1-3 on the middleground): of the 211 measured on players' snaps, 168 sit in
 * one. So for each street whose location file names more Jellisacs (street-ecology.json
 * counts.jellisac) than node-spots.json measured, it takes the street's middleground hollows that
 * no measured Jellisac sits in, left to right, and seats the rest there. Writes
 * public/js/jellisac-hole-spots-data.js: the street's whole list (the measured rows first, in
 * their order, so jellisac:<i> keeps its saved state, then the holes), which street-ecology.js
 * MEASURED_NODE_SPOTS reads over JELLISAC_SPOTS. What is left after the holes is planned as before.
 *
 *   node tools/build-jellisac-hole-spots.mjs          write
 *   node tools/build-jellisac-hole-spots.mjs --check  exit 1 if stale
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { JELLISAC_SPOTS } from '../public/js/node-spots-data.js?v=97d4281c';
import { streetEcologyAliases } from '../public/js/street-ecology.js?v=c9852cb0';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = 'public/js/jellisac-hole-spots-data.js';
const read = (rel) => JSON.parse(readFileSync(join(root, rel), 'utf8'));

/** A hollow's deco point to the Jellisac's (its frame cell bottom centre): the measured median per sprite. */
export const HOLE_LIFT = Object.freeze({ ground_cutaway_hollow1: 0, ground_cutaway_hollow2: 3, ground_cutaway_hollow3: -4 });
/** A measured Jellisac this near a hollow (px, each way) sits in it. */
export const HOLE_NEAR = 40;
/** A hole's jellySack variant, in the measured mix (120 of 211 are jellySack1, 44 jellySack2, 26 3, 21 4). */
export const HOLE_VARIANTS = Object.freeze([1, 2, 1, 3, 1, 2, 1, 4, 1, 1]);

/** PURE: a street's middleground hollows as [x, y] Jellisac points in street px, left to right. */
export function streetHoles(street) {
  const b = street?.bounds;
  if (!b || !Array.isArray(street.layers)) return [];
  const out = [];
  for (const layer of street.layers) {
    if (layer?.name !== 'middleground') continue;
    for (const d of layer.decos || []) {
      const lift = HOLE_LIFT[d?.sprite];
      if (lift == null || !Number.isFinite(d.x) || !Number.isFinite(d.y)) continue;
      out.push([d.x - b.l, d.y - b.t + lift]);
    }
  }
  return out.sort((a, c) => a[0] - c[0] || a[1] - c[1]);
}

/** PURE: the measured rows, then the holes none of them sits in, as many as `want` allows. */
export function seatInHoles(measured, holes, want) {
  const rows = measured.slice(0, want);
  const free = holes.filter(([hx, hy]) => !measured.some(([x, y]) => Math.abs(x - hx) < HOLE_NEAR && Math.abs(y - hy) < HOLE_NEAR));
  free.slice(0, Math.max(0, want - rows.length)).forEach(([x, y], i) => rows.push([x, y, HOLE_VARIANTS[i % HOLE_VARIANTS.length]]));
  return rows;
}

export function buildJellisacHoleSpots() {
  const ecology = read('public/assets/content/street-ecology.json').streets;
  const index = read('public/assets/streets/index.json').streets;
  const spots = {};
  const tally = { streets: 0, holes: 0 };
  for (const [tsid, row] of Object.entries(ecology).sort(([a], [b]) => a.localeCompare(b))) {
    const want = Number(row?.counts?.jellisac) || 0;
    if (!want || !index[tsid]) continue;
    let measured = [];
    for (const alias of streetEcologyAliases(tsid)) {
      if (JELLISAC_SPOTS[alias]?.length) { measured = JELLISAC_SPOTS[alias]; break; }
    }
    if (measured.length >= want) continue;
    const rows = seatInHoles(measured, streetHoles(read(`public/${index[tsid].file}`)), want);
    if (rows.length === Math.min(measured.length, want)) continue;
    spots[tsid] = rows;
    tally.streets += 1;
    tally.holes += rows.length - measured.length;
  }
  const lines = Object.entries(spots).map(([tsid, list]) => `  ${tsid}: Object.freeze([${list.map((r) => `[${r.join(', ')}]`).join(', ')}]),`);
  const text = `// Generated by tools/build-jellisac-hole-spots.mjs: never edit by hand.
/**
 * G933 (#453, #460): the Jellisacs of streets whose location file names more than the snaps
 * measured: [x, y, jellySack variant] in street px (the frame cell's bottom centre), the measured
 * rows (node-spots-data.js JELLISAC_SPOTS) first, then the street's empty middleground hollows
 * (ground_cutaway_hollow1-3) left to right. street-ecology.js MEASURED_NODE_SPOTS reads them
 * over JELLISAC_SPOTS; any Jellisac still without a spot is planned on a floor.
 */
export const JELLISAC_HOLE_SPOTS = Object.freeze({
${lines.join('\n')}
});
`;
  return { text, spots, tally };
}

function main() {
  const check = process.argv.includes('--check');
  const { text, tally } = buildJellisacHoleSpots();
  const out = join(root, OUT);
  let before = '';
  try { before = readFileSync(out, 'utf8'); } catch { /* new */ }
  const summary = `${tally.streets} streets, ${tally.holes} Jellisacs seated in empty holes`;
  if (check) {
    if (before !== text) {
      console.error(`${OUT} is stale: run node tools/build-jellisac-hole-spots.mjs`);
      process.exit(1);
    }
    console.log(`jellisac hole spots are current: ${summary}`);
    return;
  }
  if (before !== text) writeFileSync(out, text);
  console.log(`${OUT}: ${summary}`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
