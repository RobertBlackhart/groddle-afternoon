/**
 * Where a player can arrive on each street (register G740), for the realtime server's movewatch.go,
 * which notes a join far from all of them in its log (it never refuses one). From the game's own
 * street files (public/assets/streets/<tsid>.json): every signpost connect's and door connect's
 * arrive point into a street (js/location-navigation.js buildStreetNavigation, arrivalInTarget), and
 * the street's own signposts (converted to screen space, x - bounds.l, y - bounds.t) and doors
 * (already in screen space), where a player coming back through them stands.
 *
 * Run from the game repo root:
 *   node tools/build-realtime-entries.mjs          (write)
 *   node tools/build-realtime-entries.mjs --check  (fail when stale)
 * Writes data/entries.json in the realtime server repo (go:embed in its movewatch.go;
 * found by tools/repos.mjs: GRODDLE_SERVER_DIR, else ../groddle-afternoon-server).
 */

import { readFileSync, readdirSync } from 'node:fs';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { requireServer, serverPath } from './repos.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const streetsDir = join(root, 'public', 'assets', 'streets');
const outPath = serverPath('data', 'entries.json');

const round = (v) => Math.round(Number(v));
const ok = (p) => p && Number.isFinite(Number(p.x)) && Number.isFinite(Number(p.y));

/** Every street's entry points: { tsid: [[x, y], ...] }, sorted and without repeats. */
export function entriesData() {
  const files = readdirSync(streetsDir).filter((f) => /^[A-Z0-9_]+\.json$/.test(f) && f !== 'index.json');
  const known = new Set(files.map((f) => f.slice(0, -5)));
  // A connect names the location tsid (LA…); the game's street key is the GA… file of it.
  const keyOf = (tsid) => (known.has(tsid) ? tsid : known.has(`G${String(tsid).slice(1)}`) ? `G${String(tsid).slice(1)}` : null);
  const points = new Map();
  const add = (street, x, y) => {
    if (!street) return;
    if (!points.has(street)) points.set(street, new Set());
    points.get(street).add(`${round(x)},${round(y)}`);
  };
  for (const f of files) {
    const s = JSON.parse(readFileSync(join(streetsDir, f), 'utf8'));
    const tsid = f.slice(0, -5);
    const { l = 0, t = 0 } = s.bounds || {};
    for (const sign of s.signposts || []) {
      if (ok(sign)) add(tsid, sign.x - l, sign.y - t);
      for (const c of sign.connects || []) if (ok(c.arrive)) add(keyOf(c.tsid), c.arrive.x, c.arrive.y);
    }
    for (const door of s.doors || []) {
      if (ok(door)) add(tsid, door.x, door.y);
      if (ok(door.connect?.arrive)) add(door.connect.street || keyOf(door.connect.tsid), door.connect.arrive.x, door.connect.arrive.y);
    }
  }
  const streets = {};
  for (const tsid of [...points.keys()].sort()) {
    streets[tsid] = [...points.get(tsid)].map((p) => p.split(',').map(Number)).sort((a, b) => a[0] - b[0] || a[1] - b[1]);
  }
  return {
    about: 'Street entry points for movewatch.go in groddle-afternoon-server. Generated by tools/build-realtime-entries.mjs from public/assets/streets; do not edit by hand.',
    format: 'streets[tsid] = [[x, y]]: screen-space points where a player arrives (signpost and door arrive points into the street, its own signposts and doors)',
    streets,
  };
}

async function main() {
  requireServer();
  const out = entriesData();
  const text = `${JSON.stringify(out)}\n`;
  const n = Object.values(out.streets).reduce((k, list) => k + list.length, 0);
  if (process.argv.includes('--check')) {
    const now = await readFile(outPath, 'utf8').catch(() => '');
    if (now !== text) {
      console.error(`${outPath} is stale: run node tools/build-realtime-entries.mjs`);
      process.exit(1);
    }
    console.log(`${outPath} is current (${Object.keys(out.streets).length} streets, ${n} points)`);
    return;
  }
  await mkdir(dirname(outPath), { recursive: true });
  await writeFile(outPath, text);
  console.log(`${Object.keys(out.streets).length} streets, ${n} points -> ${outPath}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) await main();
